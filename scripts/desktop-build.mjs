import { cp, mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const output=path.resolve(process.env.ABYSSUS_BUILD_ROOT??path.join(root,'build'),'app');
if(output===path.resolve(root)||output===path.parse(output).root||path.basename(output)!=='app')throw new Error('Unsafe build output');
await rm(output,{recursive:true,force:true});
execFileSync(process.execPath,[root+'node_modules/typescript/bin/tsc','-p',root+'desktop/tsconfig.json','--outDir',output],{cwd:root,stdio:'inherit'});
await mkdir(path.join(output,'dist'),{recursive:true});
await cp(process.env.ABYSSUS_WEB_OUTPUT??root+'dist/client',path.join(output,'dist/client'),{recursive:true});
for(const file of ['entry.cjs','bootstrap.cjs','source-entry.cjs'])await cp(root+'desktop/'+file,path.join(output,'desktop',file));
await cp(root+'containers/broker',path.join(output,'containers/broker'),{recursive:true,filter:file=>!file.includes('__pycache__')&&!file.endsWith('.pyc')});
for(const file of ['worker-runner.py','worker-bridge.py','preview-http.py','container-apt.py'])await cp(root+'containers/'+file,path.join(output,'containers',file));
await mkdir(path.join(output,'helper'),{recursive:true});
for(const file of ['apt_adapter.py','core.py'])await cp(root+'helper/'+file,path.join(output,'helper',file));
const pkg=JSON.parse(await readFile(root+'package.json','utf8'));
await writeFile(path.join(output,'package.json'),JSON.stringify({name:pkg.name,version:pkg.version,type:'module',main:'desktop/entry.cjs',dependencies:pkg.dependencies,optionalDependencies:pkg.optionalDependencies}));
console.log('Desktop app staged. Bundled support runtime and exact container image manifest are staged separately.');
